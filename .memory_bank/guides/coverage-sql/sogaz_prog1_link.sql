\set ON_ERROR_STOP on
begin;

-- ═══ Приложение №1 «Амбулаторно-поликлиническое обслуживание» (003_Правила ДМС граждан) ═══
with d as (select id, insurance_company_id from program_document where storage_path='programs/sogaz_003_dms_grazhdan_2023.pdf')
insert into coverage_rule (document_id, insurance_company_id, program_name, service_class, service_pattern, verdict, condition_text, limit_amount, clause, scope_level, overridable)
select d.id, d.insurance_company_id, '«Амбулаторно-поликлиническое обслуживание» (Прил. №1 к Правилам 003)',
       v.sc, v.sp, v.vd, v.ct, null, v.cl, 'program', false
from d cross join (values
('амбулатория-приёмы','приём консультация врач терапевт хирург лор офтальмолог невролог кардиолог эндокринолог','covered','полный перечень специальностей — в пункте условий (включая челюстно-лицевую хирургию)','п. 2.1'),
('амбулатория-приёмы','телемедицинские онлайн-консультации','conditional','профилактика, анализ жалоб, решение о необходимости очного приёма, письменное заключение','п. 2.2'),
('документы-справки','оформление медицинской документации','covered',null,'п. 2.4'),
('диагностика','лабораторные исследования общеклинические биохимические иммунологические цитологические гистологические','covered',null,'п. 2.5'),
('диагностика','инструментальные исследования функциональная ультразвуковая рентген мрт эндоскопия','covered',null,'п. 2.6'),
('амбулатория-манипуляции','лечебные и диагностические манипуляции','covered',null,'п. 2.7.1'),
('физиотерапия','физиотерапевтическое восстановительное лечение аппаратное лечение','covered','объём включается в программу договора','п. 2.7.2'),
('лекарства','лекарственные средства изделия медназначения расходные материалы','covered',null,'п. 2.8'),
('амбулатория-приёмы','приёмы детских специалистов педиатрия детская хирургия эндокринология','conditional','дополнительно для детей от 0 до 18 лет','п. 2.9.1'),
('амбулатория-приёмы','динамическое наблюдение за развитием ребёнка','conditional','для детей, по нормативам Минздрава для возрастных групп','п. 2.9.2'),
('лекарства','вакцинация туберкулинодиагностика','conditional','по национальному календарю прививок, при наличии медицинских/эпидемиологических показаний','п. 2.9.3')
) as v(sc, sp, vd, ct, cl);

-- ═══ Связываем программы клиники с типовыми условиями СОГАЗ ═══
-- Точный объём определяется приложением к договору клиники (его ждём от владельца),
-- но типовые условия страховой — ближе к истине, чем «документов нет».
update program_alias set
  program_name = '«Стоматологическое обслуживание» (Прил. №5 к Правилам 003)',
  note = 'сопоставлено с типовыми условиями программы СОГАЗ (Прил. №5 к Правилам 003 от 31.01.2023); точный объём — в приложении к договору клиники, ожидается от владельца'
where alias_norm = 'стоматология в лпу'
  and insurance_company_id = (select id from insurance_company where name ilike '%СОГАЗ%');

update program_alias set
  program_name = '«Амбулаторно-поликлиническое обслуживание» (Прил. №1 к Правилам 003)',
  note = 'сопоставлено с типовыми условиями программы СОГАЗ (Прил. №1 к Правилам 003 от 31.01.2023); точный объём — в приложении к договору клиники'
where alias_norm in ('амб. взрослые', 'амб. дети от 1 до 18 лет')
  and insurance_company_id = (select id from insurance_company where name ilike '%СОГАЗ%');

select 'правил СОГАЗ 003: ' || count(*) from coverage_rule cr join program_document pd on pd.id=cr.document_id
 where pd.storage_path='programs/sogaz_003_dms_grazhdan_2023.pdf';
select 'всего правил: ' || count(*) from coverage_rule;
commit;
