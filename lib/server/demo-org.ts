import { sql, type SQL } from "drizzle-orm"

// ─────────────────────────────────────────────────────────────────────
// Граница контуров: демо-стенд ↔ рабочий контур (ADR D50, требование владельца 11.08:
// «чтоб в рабочий контур ничего не попадало из демо»).
//
// Правило одно и оно здесь единственным экземпляром:
//   • выбрана конкретная клиника  → показываем ровно её (в т.ч. демо — стенд должен работать);
//   • режим «все клиники»         → ТОЛЬКО рабочий контур, демо-организации исключены всегда.
//
// Признак — `organization.is_demo` в БД, а не совпадение названия «Демо-клиника»: переименование
// стенда раньше молча ломало границу. Пока правило жило копиями в реестре и дайджесте, страницы
// покрытия его не применяли — владельцу показывалась доля 53% вместо 79% (разбор 11.08).
// Тест `demo-isolation.test.ts` следит, чтобы новый модуль не забыл этот фильтр.
// Без `server-only`: это чистые SQL-построители, ими пользуются и CLI-скрипты (ТГ-дайджест).
// ─────────────────────────────────────────────────────────────────────

/** Только рабочий контур: организация записи не помечена как демо. */
export const liveOrgsOnly = (orgIdColumn: SQL): SQL =>
  sql`${orgIdColumn} in (select id from organization where not is_demo)`

/**
 * Единственный способ ограничить выборку по клинике. Забыть про демо нельзя: режим «все клиники»
 * (orgId = null) сам подставляет фильтр рабочего контура.
 * @param orgId null = все клиники рабочего контура; uuid = конкретная клиника (демо тоже).
 */
export const orgScope = (orgIdColumn: SQL, orgId: string | null): SQL =>
  orgId ? sql`${orgIdColumn} = ${orgId}` : liveOrgsOnly(orgIdColumn)
