import "server-only"
import { sql, type SQL } from "drizzle-orm"

// ─────────────────────────────────────────────────────────────────────
// Демо-организация (стенд продаж, ADR D22). В админском режиме «все клиники» (orgId=null)
// её записи СКРЫВАЕМ везде, где считаются цифры: иначе синтетика стенда подмешивается в
// боевые счётчики. Видна только при явном выборе демо-клиники.
//
// Правило жило в двух копиях (реестр и ТГ-дайджест), а страницы покрытия его не применяли —
// из-за этого доля найденных правил показывалась 53% вместо 79% (11.08). Держим в одном месте.
// ─────────────────────────────────────────────────────────────────────

export const DEMO_ORG_NAME = "Демо-клиника"

/** Предикат «запись не из демо-организации». Колонку передаём выражением — таблица бывает с алиасом. */
export const notDemoOrg = (orgIdColumn: SQL): SQL =>
  sql`${orgIdColumn} not in (select id from organization where name = ${DEMO_ORG_NAME})`
