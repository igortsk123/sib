export const MAX_ROOT_WORDS = 3
export const MIN_ROOT_LEN = 3

export function words(s: string): string[] {
  return s.toLowerCase().match(/[а-яёa-z0-9]+/g) ?? []
}

export function isCore(word: string): boolean {
  return CORE_STEMS.some((c) => word.startsWith(c.slice(0, Math.max(3, c.length - 1))))
}

/**
 * Эмуляция минус-фразы Директа: ВСЕ слова корня должны найтись во фразе в любой словоформе.
 * Словоформа = общая основа (слово минус 2 буквы) + слово во фразе не длиннее корня на 3 буквы.
 * Ограничение длины обязательно: без него «автомоб» ложно совпал бы с «автоматизацией»
 * и робот заминусовал бы собственную целевую фразу.
 */
export function blocks(root: string, phrase: string): boolean {
  const pw = words(phrase)
  return words(root).every((w) => {
    const stem = w.slice(0, Math.max(4, w.length - 2))
    return pw.some((q) => q.startsWith(stem) && q.length <= w.length + 3)
  })
}

/** Защита = активные фразы кампаний (без автотаргетинга и кавычек) + канарейки. */
export function buildProtection(activeKeywords: string[]): string[] {
  return [
    ...activeKeywords
      .filter((k) => k !== "---autotargeting")
      .map((k) => k.replace(/["!]/g, "").trim().toLowerCase())
      .filter(Boolean),
    ...CANARY,
  ]
}

export type Rejected = { root: string; reason: string }

export type FilterInput = {
  roots: string[]
  protection: string[]
  /** Уже применённые минус-слова кампании. */
  existing?: string[]
  /** Мусорные запросы текущей пачки — для правила «маркер класса». */
  corpus?: string[]
  /** Те из corpus, за клики по которым уже заплачено. */
  paid?: string[]
}

/**
 * Одиночный корень принимается, если ловит ≥2 запроса (маркер класса) ИЛИ хотя бы один
 * платный (за него уже уплачены деньги — точечный минус оправдан).
 */
export function filterRoots(input: FilterInput): { accepted: string[]; rejected: Rejected[] } {
  const { roots, protection, existing = [], corpus = [], paid = [] } = input
  const accepted: string[] = []
  const rejected: Rejected[] = []
  const seen = new Set<string>()
  const existingLow = new Set(existing.map((e) => e.toLowerCase().replace(/^!/, "").trim()))

  for (const raw of roots) {
    const ws = words(raw)
    const root = ws.join(" ")
    if (!root) {
      rejected.push({ root: raw, reason: "пусто" })
      continue
    }
    if (seen.has(root)) continue
    seen.add(root)

    if (ws.length > MAX_ROOT_WORDS) {
      rejected.push({ root, reason: `длиннее ${MAX_ROOT_WORDS} слов` })
      continue
    }
    if (existingLow.has(root)) {
      rejected.push({ root, reason: "уже есть" })
      continue
    }
    if (ws.length > 1 && ws.every(isCore)) {
      rejected.push({ root, reason: "фраза целиком из ядра ниши" })
      continue
    }
    if (ws.length === 1) {
      if (ws[0]!.length < MIN_ROOT_LEN) {
        rejected.push({ root, reason: "слишком короткий" })
        continue
      }
      if (isCore(ws[0]!)) {
        rejected.push({ root, reason: "ядро ниши — нельзя минусовать одиночным словом" })
        continue
      }
      if (TOO_GENERAL.has(ws[0]!)) {
        rejected.push({ root, reason: "слишком общее слово" })
        continue
      }
      if (corpus.length) {
        const hits = corpus.filter((q) => blocks(root, q)).length
        if (hits < 2 && !paid.some((q) => blocks(root, q))) {
          rejected.push({ root, reason: "ловит один бесплатный запрос — не маркер класса" })
          continue
        }
      }
    }
    const hit = protection.find((p) => blocks(root, p))
    if (hit) {
      rejected.push({ root, reason: `заблокировал бы «${hit}»` })
      continue
    }
    accepted.push(root)
  }
  return { accepted, rejected }
}
